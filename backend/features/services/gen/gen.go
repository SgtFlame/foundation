// Package gen writes the proxy and server of every service (forge 21a-2,
// documentation/Services.md): it reads each
// features/**/services/<s>service/Service.go and writes, beside it,
// proxy/proxy.go and server/server.go, and a catalog of every service in
// features/services/catalog. The code is generated, never written by
// hand, so a new operation travels the moment it is declared; Check fails
// when what is checked in is stale.
package gen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Header starts every generated file.
const Header = "// Code generated by cli gen services. DO NOT EDIT.\n\n"

// Markers on an operation's doc comment in the Service interface.
const (
	MarkLocal      = "//svc:local"      // only Go code in the same process calls it
	MarkIdempotent = "//svc:idempotent" // safe to send twice: retried when no server answers
	MarkStream     = "//svc:stream"     // hands back a channel; travels as a stream (forge 21c)
	MarkJob        = "//svc:job"        // may run for minutes: a candidate for running as a job
)

// Op is one operation of a service's interface.
type Op struct {
	Name       string
	Args       string // the <Op>Args type, in the service's package
	Result     string // the result type, "" when none; "*X" for a pointer
	Local      bool
	Idempotent bool
	Stream     bool
	Job        bool
}

// Embedded is an interface the Service interface embeds, such as
// config.Reader: the proxy holds it as a field the caller sets.
type Embedded struct {
	Pkg, Name string // the package's import path and the interface's name
	Alias     string // the package's name in the file
}

// Service is one service as the generator reads it.
type Service struct {
	Name     string // the wire name: the package's name without "service"
	Pkg      string // the package's name, <s>service
	Import   string // its import path
	Dir      string // its directory
	Ops      []Op
	Embedded []Embedded
	Manifest bool // its package declares var Manifest (forge 21f-1)
}

// Options say where to read and write.
type Options struct {
	Root   string   // the module's root directory (backend)
	Module string   // the module path; read from go.mod when empty
	Dirs   []string // directories under Root to search (features)
	// Catalog is the directory, under Root, of the generated catalog
	// (features/services/catalog).
	Catalog string
	// Services is the import path of package services, for a module other
	// than Foundation's.
	Services string
}

const foundationServices = "github.com/SgtFlame/foundation/backend/features/services"

func (o *Options) fill() error {
	if len(o.Dirs) == 0 {
		o.Dirs = []string{"features"}
	}
	if o.Catalog == "" {
		o.Catalog = filepath.Join("features", "services", "catalog")
	}
	if o.Services == "" {
		o.Services = foundationServices
	}
	if o.Module == "" {
		b, err := os.ReadFile(filepath.Join(o.Root, "go.mod"))
		if err != nil {
			return err
		}
		for _, line := range strings.Split(string(b), "\n") {
			if strings.HasPrefix(line, "module ") {
				o.Module = strings.TrimSpace(strings.TrimPrefix(line, "module "))
			}
		}
		if o.Module == "" {
			return fmt.Errorf("%s/go.mod names no module", o.Root)
		}
	}
	return nil
}

// Read finds and reads every service under the options' directories.
func Read(o Options) ([]Service, error) {
	if err := o.fill(); err != nil {
		return nil, err
	}
	var out []Service
	for _, d := range o.Dirs {
		err := filepath.WalkDir(filepath.Join(o.Root, d), func(path string, e os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if e.IsDir() || e.Name() != "Service.go" {
				return nil
			}
			dir := filepath.Dir(path)
			pkg := filepath.Base(dir)
			if !strings.HasSuffix(pkg, "service") || filepath.Base(filepath.Dir(dir)) != "services" {
				return nil
			}
			s, err := readService(o, dir, path)
			if err != nil {
				return err
			}
			if s != nil {
				out = append(out, *s)
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	seen := map[string]string{}
	for _, s := range out {
		if other, ok := seen[s.Name]; ok {
			return nil, fmt.Errorf("services %s and %s have the same wire name %q", other, s.Import, s.Name)
		}
		seen[s.Name] = s.Import
	}
	return out, nil
}

func readService(o Options, dir, path string) (*Service, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	rel, err := filepath.Rel(o.Root, dir)
	if err != nil {
		return nil, err
	}
	s := &Service{Pkg: f.Name.Name, Import: o.Module + "/" + filepath.ToSlash(rel), Dir: dir}
	s.Name = strings.TrimSuffix(s.Pkg, "service")
	if raw, err := os.ReadFile(filepath.Join(dir, "Manifest.go")); err == nil && strings.Contains(string(raw), "var Manifest") {
		s.Manifest = true
	}
	imports := map[string]string{}
	for _, im := range f.Imports {
		p := strings.Trim(im.Path.Value, `"`)
		name := p[strings.LastIndex(p, "/")+1:]
		if im.Name != nil {
			name = im.Name.Name
		}
		imports[name] = p
	}
	var iface *ast.InterfaceType
	ast.Inspect(f, func(n ast.Node) bool {
		if ts, ok := n.(*ast.TypeSpec); ok && ts.Name.Name == "Service" {
			iface, _ = ts.Type.(*ast.InterfaceType)
		}
		return iface == nil
	})
	if iface == nil {
		return nil, nil
	}
	pos := func(n ast.Node) string { return fset.Position(n.Pos()).String() }
	for _, m := range iface.Methods.List {
		if len(m.Names) == 0 {
			sel, ok := m.Type.(*ast.SelectorExpr)
			if !ok {
				return nil, fmt.Errorf("%s: an embedded interface must come from another package", pos(m))
			}
			alias := sel.X.(*ast.Ident).Name
			s.Embedded = append(s.Embedded, Embedded{Pkg: imports[alias], Name: sel.Sel.Name, Alias: alias})
			continue
		}
		ft := m.Type.(*ast.FuncType)
		op := Op{Name: m.Names[0].Name}
		if m.Doc != nil {
			for _, c := range m.Doc.List {
				switch strings.TrimSpace(c.Text) {
				case MarkLocal:
					op.Local = true
				case MarkIdempotent:
					op.Idempotent = true
				case MarkStream:
					op.Stream = true
				case MarkJob:
					op.Job = true
				}
			}
		}
		shapeOK := false
		if ft.Params != nil && len(ft.Params.List) == 1 && len(ft.Params.List[0].Names) <= 1 {
			if id, ok := ft.Params.List[0].Type.(*ast.Ident); ok {
				op.Args = id.Name
				shapeOK = true
			}
		}
		if ft.Results != nil {
			if len(ft.Results.List) != 1 {
				shapeOK = false
			} else {
				switch r := ft.Results.List[0].Type.(type) {
				case *ast.Ident:
					op.Result = r.Name
				case *ast.StarExpr:
					if id, ok := r.X.(*ast.Ident); ok {
						op.Result = "*" + id.Name
					} else {
						shapeOK = false
					}
				default:
					shapeOK = false
				}
			}
		}
		if !shapeOK {
			if !op.Local {
				return nil, fmt.Errorf("%s: %s.%s cannot travel: an operation takes one <Op>Args and returns one response; mark it %s", pos(m), s.Pkg, op.Name, MarkLocal)
			}
			return nil, fmt.Errorf("%s: %s.%s: even a local operation takes one <Op>Args of its own package", pos(m), s.Pkg, op.Name)
		}
		if !op.Local && !op.Stream && (op.Result == "" || strings.HasPrefix(op.Result, "*")) {
			return nil, fmt.Errorf("%s: %s.%s cannot travel: it returns %q; mark it %s, or %s if it hands back a channel", pos(m), s.Pkg, op.Name, op.Result, MarkLocal, MarkStream)
		}
		s.Ops = append(s.Ops, op)
	}
	return s, nil
}

// Files are the generated files, by path relative to the root.
type Files map[string][]byte

// Generate reads every service and returns the files it writes.
func Generate(o Options) (Files, error) {
	if err := o.fill(); err != nil {
		return nil, err
	}
	svcs, err := Read(o)
	if err != nil {
		return nil, err
	}
	files := Files{}
	for _, s := range svcs {
		rel, _ := filepath.Rel(o.Root, s.Dir)
		p, err := proxyFile(o, s)
		if err != nil {
			return nil, err
		}
		files[filepath.Join(rel, "proxy", "proxy.go")] = p
		sv, err := serverFile(o, s)
		if err != nil {
			return nil, err
		}
		files[filepath.Join(rel, "server", "server.go")] = sv
	}
	c, err := catalogFile(o, svcs)
	if err != nil {
		return nil, err
	}
	files[filepath.Join(o.Catalog, "catalog.go")] = c
	return files, nil
}

// Write generates and writes every file.
func Write(o Options) (Files, error) {
	files, err := Generate(o)
	if err != nil {
		return nil, err
	}
	for rel, b := range files {
		path := filepath.Join(o.Root, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, err
		}
		if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, b) {
			continue
		}
		if err := os.WriteFile(path, b, 0o644); err != nil {
			return nil, err
		}
	}
	return files, nil
}

// Check generates every file and lists those that differ from what is
// written, each with why.
func Check(o Options) ([]string, error) {
	files, err := Generate(o)
	if err != nil {
		return nil, err
	}
	var stale []string
	for rel, b := range files {
		old, err := os.ReadFile(filepath.Join(o.Root, rel))
		switch {
		case err != nil:
			stale = append(stale, rel+": missing")
		case !bytes.Equal(old, b):
			stale = append(stale, rel+": stale")
		}
	}
	sort.Strings(stale)
	return stale, nil
}

func formatted(name string, b []byte) ([]byte, error) {
	out, err := format.Source(b)
	if err != nil {
		return nil, fmt.Errorf("%s: %v\n%s", name, err, b)
	}
	return out, nil
}
